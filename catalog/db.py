import os
import sqlite3
from contextlib import contextmanager
from pathlib import Path

DATA = Path(os.getenv("DATA_DIR", "data")).resolve()
DATABASE_URL = os.getenv("DATABASE_URL")

SCHEMA = """
CREATE TABLE IF NOT EXISTS products (
    id INTEGER PRIMARY KEY,
    sku TEXT NOT NULL,
    sku_key TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    description TEXT NOT NULL,
    active INTEGER NOT NULL CHECK (active IN (0, 1))
);
CREATE INDEX IF NOT EXISTS products_status_page ON products(active, id);
CREATE UNIQUE INDEX IF NOT EXISTS products_sku_ci ON products(LOWER(TRIM(sku)));
CREATE TABLE IF NOT EXISTS webhooks (
    id INTEGER PRIMARY KEY,
    url TEXT NOT NULL,
    events TEXT NOT NULL,
    enabled INTEGER NOT NULL CHECK (enabled IN (0, 1))
);
CREATE TABLE IF NOT EXISTS jobs (
    id TEXT PRIMARY KEY,
    kind TEXT NOT NULL,
    state TEXT NOT NULL,
    stage TEXT NOT NULL,
    progress INTEGER NOT NULL DEFAULT 0,
    rows_processed INTEGER NOT NULL DEFAULT 0,
    payload TEXT NOT NULL,
    result TEXT,
    error TEXT,
    created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS job_queue ON jobs(state, created_at);
"""

class Database:
    def __init__(self, raw):
        self.raw = raw

    def execute(self, query, params=()):
        return self.raw.execute(query.replace("?", "%s") if DATABASE_URL else query, params)

    def many(self, query, rows):
        with_cursor = self.raw.cursor()
        try:
            with_cursor.executemany(query.replace("?", "%s") if DATABASE_URL else query, rows)
        finally:
            with_cursor.close()


@contextmanager
def connect():
    if DATABASE_URL:
        import psycopg
        from psycopg.rows import dict_row
        raw = psycopg.connect(DATABASE_URL, row_factory=dict_row)
    else:
        raw = sqlite3.connect(DATA / "catalog.sqlite3", timeout=15)
        raw.row_factory = sqlite3.Row
        raw.execute("PRAGMA busy_timeout=15000")
    try:
        yield Database(raw)
        raw.commit()
    except BaseException:
        raw.rollback()
        raise
    finally:
        raw.close()


def initialize():
    DATA.mkdir(parents=True, exist_ok=True)
    (DATA / "uploads").mkdir(exist_ok=True)
    with connect() as db:
        if DATABASE_URL:
            db.execute("SELECT pg_advisory_xact_lock(782419)")
        else:
            db.execute("PRAGMA journal_mode=WAL")
        for sql in SCHEMA.split(";"):
            if sql.strip():
                if DATABASE_URL:
                    sql = sql.replace("id INTEGER PRIMARY KEY", "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
                db.execute(sql)

